/*
 * Exercício - Uso de comentários em C
 * Este programa exibe o valor do número de Euler formatado com 3 casas decimais.
 */

#include <stdio.h> /* Inclui a biblioteca para a função printf() */

int main() /* Função principal do programa */
{ /* Início do corpo da função main */

    float euler = 2.71828; // Declaração da variável float

    printf("O valor do numero de Euler e de: %.3f.\n", euler); // Chamada à função printf 
    return 0; // Retorna 0 
} /* Fim do corpo da função main */